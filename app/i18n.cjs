function has(lang) { return UI_LANGS.includes(lang); }

function t(lang, key, vars) {
  const table = STRINGS[has(lang) ? lang : 'en'];
  let out = table[key];
  if (out == null) out = STRINGS.en[key];
  if (out == null) return null;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k])));
  return out;
}

// Translate a rendered document by walking the marked attributes. Only elements carrying a key are
// touched, so markup, class names and anything without a translation survive unchanged.
function apply(html, lang) {
  if (!has(lang) || lang === 'en') return html;
  const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  return html
    .replace(/(<([a-z0-9-]+)\b[^>]*\bdata-i18n="([^"]+)"[^>]*>)([\s\S]*?)(<\/\2>)/gi, (m, open, tag, key, _inner, close) => {
      const v = t(lang, key);
      return v == null ? m : open + esc(v) + close;
    })
    .replace(/(<([a-z0-9-]+)\b[^>]*\bdata-i18n-ph="([^"]+)"[^>]*>)/gi, (m, open, tag, key) => {
      const v = t(lang, key);
      return v == null ? m : open.replace(/placeholder="[^"]*"/, `placeholder="${esc(v)}"`);
    })
    .replace(/(<([a-z0-9-]+)\b[^>]*\bdata-i18n-aria="([^"]+)"[^>]*>)/gi, (m, open, tag, key) => {
      const v = t(lang, key);
      return v == null ? m : open.replace(/aria-label="[^"]*"/, `aria-label="${esc(v)}"`);
    });
}

